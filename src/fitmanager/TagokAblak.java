    private void btnTagMenteseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTagMenteseActionPerformed
        // TODO add your handling code here:

        // A tag adatainak beolvasása
        String nev = txtNev.getText().trim();
        String telefon = txtTelefon.getText().trim();
        String email = txtEmail.getText().trim();
        String azonosito = txtTagAzonosito.getText().trim();

        if (nev.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Kérlek, add meg a tag nevét!");
            return;
        }

        if (telefon.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Kérlek, add meg a telefonszámot!");
            return;
        }

        if (email.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Kérlek, add meg az e-mail-címet!");
            return;
        }

        if (azonosito.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Kérlek, add meg a tagsági azonosítót!");
            return;
        }

        try {
            AdatbazisKezelo.tagMentese(nev, telefon, email, azonosito);

            tagokListaFrissitese();

            javax.swing.JOptionPane.showMessageDialog(
                    this, "A tag adatai sikeresen elmentve!");

            txtNev.setText("");
            txtTelefon.setText("");
            txtEmail.setText("");
            txtTagAzonosito.setText("");

        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Nem sikerült elmenteni a tagot: " + ex.getMessage(),
                    "Mentési hiba",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }


    }//GEN-LAST:event_btnTagMenteseActionPerformed

    private void txtKeresesKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtKeresesKeyReleased
        // TODO add your handling code here:
        String keresettSzoveg = txtKereses.getText().trim();

        javax.swing.table.TableRowSorter<javax.swing.table.TableModel> rendezo
                = new javax.swing.table.TableRowSorter<>(tblTagok.getModel());

        tblTagok.setRowSorter(rendezo);

        if (!keresettSzoveg.isEmpty()) {
            rendezo.setRowFilter(
                    javax.swing.RowFilter.regexFilter(
                            "(?iu)" + java.util.regex.Pattern.quote(keresettSzoveg),
                            1, 4
                    )
            );
    }//GEN-LAST:event_txtKeresesKeyReleased
    }

    private void btnTagModositasaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTagModositasaActionPerformed
        // TODO add your handling code here:
        int kijeloltSor = tblTagok.getSelectedRow();

        if (kijeloltSor == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Először válassz ki egy tagot a táblázatból!");
            return;
        }

        int modellSor = tblTagok.convertRowIndexToModel(kijeloltSor);

        int id = ((Number) tblTagok.getModel()
                .getValueAt(modellSor, 0)).intValue();

        String nev = txtNev.getText().trim();
        String telefon = txtTelefon.getText().trim();
        String email = txtEmail.getText().trim();
        String azonosito = txtTagAzonosito.getText().trim();

        if (nev.isEmpty() || telefon.isEmpty()
                || email.isEmpty() || azonosito.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Minden mező kitöltése kötelező!");
            return;
        }

        try {
            AdatbazisKezelo.tagModositasa(
                    id, nev, telefon, email, azonosito);

            tagokListaFrissitese();

            javax.swing.JOptionPane.showMessageDialog(
                    this, "A tag adatai sikeresen módosítva!");

            txtNev.setText("");
            txtTelefon.setText("");
            txtEmail.setText("");
            txtTagAzonosito.setText("");

        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Nem sikerült módosítani a tagot: " + ex.getMessage(),
                    "Módosítási hiba",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnTagModositasaActionPerformed

    private void tblTagokMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblTagokMouseClicked
        // TODO add your handling code here:
        int kijeloltSor = tblTagok.getSelectedRow();

        if (kijeloltSor == -1) {
            return;
        }

        int modellSor = tblTagok.convertRowIndexToModel(kijeloltSor);

        javax.swing.table.TableModel modell = tblTagok.getModel();

        txtNev.setText(modell.getValueAt(modellSor, 1).toString());
        txtTelefon.setText(modell.getValueAt(modellSor, 2).toString());
        txtEmail.setText(modell.getValueAt(modellSor, 3).toString());
        txtTagAzonosito.setText(modell.getValueAt(modellSor, 4).toString());

    }//GEN-LAST:event_tblTagokMouseClicked

