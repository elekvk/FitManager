    private void btnBelepesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBelepesActionPerformed
        // TODO add your handling code here:
        if (cmbTagok.getSelectedItem() == null) {
            lblEredmeny.setText("Válassz ki egy tagot!");
            return;
        }

        try {
            String tag = cmbTagok.getSelectedItem().toString();
            int elvalaszto = tag.indexOf(" - ");

            int tagId = Integer.parseInt(
                    tag.substring(0, elvalaszto)
            );

            if (AdatbazisKezelo.vanErvenyesBerlet(tagId)) {
                AdatbazisKezelo.belepesMentese(tagId); 
    
                lblEredmeny.setText("Belépés engedélyezve");
                lblEredmeny.setForeground(
                        java.awt.Color.GREEN
                );
            } else {
                lblEredmeny.setText("Nincs érvényes bérlet!");
                lblEredmeny.setForeground(
                        java.awt.Color.RED
                );
            }

        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Adatbázishiba: " + ex.getMessage()
            );
        } catch (IllegalArgumentException ex) {
            lblEredmeny.setText("Hibás tagazonosító!");
        }
    }//GEN-LAST:event_btnBelepesActionPerformed

