    private void kimutatasokBetoltese() {
        try {
            int tagok = AdatbazisKezelo.osszesDarab("TAGOK");
            int berletek = AdatbazisKezelo.osszesDarab("BERLETEK");
            int belepesek = AdatbazisKezelo.osszesDarab("BELEPESEK");

            lblTagokSzama.setText(String.valueOf(tagok));
            lblBerletekSzama.setText(String.valueOf(berletek));
            lblBelepesekSzama.setText(String.valueOf(belepesek));

        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Nem sikerült betölteni a kimutatásokat: "
                    + ex.getMessage(),
                    "Adatbázishiba",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }

